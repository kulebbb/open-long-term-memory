def header_for(rel: str) -> str:
    """Return the generated page header for a repository-relative path."""
    if rel in MOC_HEADERS:
        return MOC_HEADERS[rel]
    if rel.startswith(PROJECT_PAGE_PREFIX) and rel.endswith(".md"):
        slug = rel[len(PROJECT_PAGE_PREFIX): -len(".md")]
        return (
            f"# {slug} (Project MOC)\n"
            "\n"
            f"Facts, related people, and open work for the `{slug}` project.\n"
            "Generated by the indexer; do not edit by hand.\n"
            "\n"
        )
    return INDEX_HEADER


@dataclass
class Entry:
    path: str  # Repository-relative POSIX path.
    id: str
    type: str
    status: str
    created: str
    updated: str
    summary: str
    projects: list[str]
    people: list[str]
    tags: list[str]
    links: list[str]
    contradicts: list[str]
    supersedes: str | None


class MarkersMissing(Exception):
    def __init__(self, rel: str) -> None:
        super().__init__(rel)
        self.rel = rel


class IndexReadError(Exception):
    def __init__(self, rel: str, detail: str) -> None:
        super().__init__(detail)
        self.rel = rel
        self.detail = detail


def inside_root(path: Path) -> bool:
    try:
        return path.resolve().is_relative_to(ROOT.resolve())
    except OSError:
        return False


def valid_date(value: str) -> bool:
    if not DATE_RE.match(value):
        return False
    try:
        date.fromisoformat(value)
    except ValueError:
        return False
    return True


def unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value


def split_inline_list(inner: str) -> list[str]:
    """Split an inline YAML-like list without splitting commas in quotes."""
    items: list[str] = []
    buf: list[str] = []
    quote: str | None = None
    for char in inner:
        if quote:
            buf.append(char)
            if char == quote:
                quote = None
        elif char in "'\"":
            quote = char
            buf.append(char)
        elif char == ",":
            items.append("".join(buf))
            buf = []
        else:
            buf.append(char)
    items.append("".join(buf))
    return [unquote(item.strip()) for item in items if item.strip()]


def parse_value(raw: str):
    value = raw.strip()
    if value.startswith("#"):
        value = ""  # A comment-only value is empty.
    # Strip trailing comments from both quoted and unquoted scalar values.
    if value.startswith(("'", '"')):
        quote = value[0]
        end = value.find(quote, 1)
        if end != -1:
            value = value[: end + 1]
    elif " #" in value:
        value = value.split(" #", 1)[0].rstrip()
    if value in {"", "~", "null", "Null", "NULL"}:
        return None
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        if not inner:
            return []
        return split_inline_list(inner)
    return unquote(value)


def parse_frontmatter(text: str) -> tuple[dict, str]:
    match = FM_RE.match(text)
    if not match:
        raise ValueError("missing frontmatter (the file must begin and end the block with ---)")
    fields: dict[str, object] = {}
    list_key: str | None = None
    for line in match.group(1).splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        # Block list: projects:\n  - sample-app
        if stripped.startswith("- ") and list_key is not None:
            value = fields.get(list_key)
            if not isinstance(value, list):
                value = []
            item = parse_value(stripped[2:])
            value.append("" if item is None else item)
            fields[list_key] = value
            continue
        list_key = None
        if ":" not in stripped:
            raise ValueError(f"cannot parse frontmatter line: {line!r}")
        key, raw = stripped.split(":", 1)
        key = key.strip()
        if not key:
            raise ValueError(f"frontmatter line has no field name: {line!r}")
        if key in fields:
            raise ValueError(f"duplicate frontmatter field: `{key}`")
        value = parse_value(raw)
        fields[key] = value
        if value is None and key in LIST_KEYS and (not raw.strip() or raw.strip().startswith("#")):
            list_key = key  # The following `- item` lines form a block list.
    return fields, text[match.end():]


def summary_of(body: str, limit: int = SUMMARY_LIMIT) -> str:
    """Use the first non-empty, non-heading, non-comment body line as summary."""
    in_comment = False
    for raw in body.splitlines():
        line = raw.strip()
        if in_comment:
            if "-->" in line:
                in_comment = False
            continue
        if line.startswith("<!--"):
            if "-->" not in line:
                in_comment = True
            continue
        if not line or line.startswith("#"):
            continue
        line = re.sub(r"^(?:结论|Conclusion)[:：]\s*", "", line)
        line = LINK_RE.sub(r"\1", line)
        line = line.replace("`", "").replace("**", "").replace("__", "")
        line = re.sub(r"\s+", " ", line).strip()
        if len(line) > limit:
            line = line[:limit].rstrip() + "…"
        return line
    return ""


def as_list(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(item) for item in value if str(item).strip()]
    return [str(value)]


def git_visible_files() -> set[str] | None:
    """Return files Git would include: tracked plus unignored untracked files.

    Ignored drafts must never leak into a committed index. Outside a Git
    repository, return None and fall back to scanning the filesystem.
    """
    try:
        top = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        if not top or Path(top).resolve() != ROOT:
            return None
        raw = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True,
            check=True,
        ).stdout.decode("utf-8", "replace")
    except (OSError, subprocess.CalledProcessError):
        return None
    return {item for item in raw.split("\0") if item}


def load_entries(errors: list[str], warnings: list[str]) -> list[Entry]:
    entries: list[Entry] = []
    seen_ids: dict[str, str] = {}
    visible = git_visible_files()
    if visible is None:
        warnings.append(
            "no Git repository detected (or Git is unavailable); scanning filesystem and ignoring .gitignore"
        )
    skipped_ignored: list[str] = []
    skipped_symlinks: list[str] = []
    for dirname in CONTENT_DIRS:
        base = ROOT / dirname
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.md")):
            rel = path.relative_to(ROOT).as_posix()
            name = path.name
            if name.startswith("_") or name.startswith("."):
                continue  # Templates and hidden files are not indexed.
            if path.is_symlink():
                skipped_symlinks.append(rel)
                continue
            if visible is not None and rel not in visible:
                skipped_ignored.append(rel)
                continue
            try:
                text = path.read_text(encoding="utf-8")
                fields, body = parse_frontmatter(text)
            except (OSError, UnicodeDecodeError, ValueError) as exc:
                errors.append(f"{rel}: {exc}")
                continue

            for required in ("id", "type", "status", "created", "author"):
                if not fields.get(required):
                    errors.append(f"{rel}: frontmatter is missing required field `{required}`")
            author = str(fields.get("author") or "").strip()
            if author and len(author) > 40:
                warnings.append(
                    f"{rel}: author is too long ({len(author)} characters); use a short agent name"
                )
            entry_id = str(fields.get("id") or "")
            if entry_id and not ID_RE.match(entry_id):
                errors.append(
                    f"{rel}: id `{entry_id}` may contain only lowercase letters, digits, and hyphens"
                )
            if entry_id and path.stem != entry_id:
                errors.append(f"{rel}: filename must equal id (expected `{entry_id}.md`)")
            if entry_id:
                if entry_id in seen_ids:
                    errors.append(f"{rel}: duplicate id `{entry_id}` (also in `{seen_ids[entry_id]}`)")
                seen_ids.setdefault(entry_id, rel)

            entry_type = str(fields.get("type") or "")
            if entry_type and entry_type not in TYPES:
                errors.append(f"{rel}: type `{entry_type}` is not one of {sorted(TYPES)}")
            expected_type = DIR_TYPES.get(rel.split("/", 1)[0])
            if entry_type and expected_type and entry_type != expected_type:
                errors.append(
                    f"{rel}: type `{entry_type}` does not match directory "
                    f"`{rel.split('/', 1)[0]}/` (expected `{expected_type}`)"
                )
            source = fields.get("source")
            if source is not None and str(source) not in SOURCES:
                warnings.append(f"{rel}: source `{source}` is not one of {sorted(SOURCES)}")
            status = str(fields.get("status") or "")
            if status and status not in STATUSES:
                errors.append(f"{rel}: status `{status}` is not one of {sorted(STATUSES)}")

            created = str(fields.get("created") or "")
            updated = str(fields.get("updated") or created)
            if created and not valid_date(created):
                errors.append(f"{rel}: created must be a valid YYYY-MM-DD date; got `{created}`")
            if updated and not valid_date(updated):
                errors.append(f"{rel}: updated must be a valid YYYY-MM-DD date; got `{updated}`")
            if not fields.get("updated"):
                warnings.append(f"{rel}: add an `updated` field")

            supersedes = fields.get("supersedes")
            supersedes = str(supersedes) if supersedes else None

            entries.append(
                Entry(
                    path=rel,
                    id=entry_id,
                    type=entry_type,
                    status=status,
                    created=created,
                    updated=updated,
                    summary=summary_of(body),
                    projects=as_list(fields.get("projects")),
                    people=as_list(fields.get("people")),
                    tags=as_list(fields.get("tags")),
                    links=as_list(fields.get("links")),
                    contradicts=as_list(fields.get("contradicts")),
                    supersedes=supersedes,
                )
            )
    if skipped_ignored:
        preview = ", ".join(skipped_ignored[:5]) + (" …" if len(skipped_ignored) > 5 else "")
        warnings.append(
            f"{len(skipped_ignored)} memory file(s) ignored by .gitignore and omitted from index: {preview}"
        )
    if skipped_symlinks:
        preview = ", ".join(skipped_symlinks[:5]) + (" …" if len(skipped_symlinks) > 5 else "")
        warnings.append(f"{len(skipped_symlinks)} symbolic link(s) omitted from index: {preview}")
    for entry in entries:
        if entry.path.startswith("projects/") and entry.path.count("/") == 1:
            warnings.append(
                f"{entry.path}: Markdown directly under projects/ is not part of a project "
                "and will not be indexed; move it to projects/<slug>/"
            )
    return entries


def validate_relations(entries: list[Entry], errors: list[str], warnings: list[str]) -> None:
    by_id = {entry.id: entry for entry in entries if entry.id}
    project_dirs = {p.name for p in (ROOT / "projects").glob("*") if p.is_dir()} if (ROOT / "projects").is_dir() else set()
    if not project_dirs and any(entry.projects for entry in entries):
        warnings.append("no project directories found under projects/; project anchors were not checked")

    for entry in entries:
        own_slug = None
        if entry.path.startswith("projects/") and entry.path.count("/") >= 2:
            own_slug = entry.path.split("/")[1]
        for target in entry.links:
            if target not in by_id:
                errors.append(f"{entry.path}: links points to missing id `{target}`")
        for target in entry.contradicts:
            if target not in by_id:
                errors.append(f"{entry.path}: contradicts points to missing id `{target}`")
        if entry.supersedes:
            target = by_id.get(entry.supersedes)
            if target is None:
                errors.append(f"{entry.path}: supersedes points to missing id `{entry.supersedes}`")
            elif target.status == "active":
                warnings.append(
                    f"{entry.path}: supersedes `{entry.supersedes}`, but the target is still "
                    "`active` (it should be `superseded`)"
                )
        for slug in entry.projects:
            if slug == own_slug:
                continue  # A project file may refer to its own directory.
            if project_dirs and slug not in project_dirs:
                errors.append(
                    f"{entry.path}: projects entry `{slug}` has no matching directory under projects/ "
                    "(a typo would make the fact disappear from project navigation)"
                )
        for person in entry.people:
            if person not in by_id or by_id[person].type != "person":
                warnings.append(f"{entry.path}: people entry `{person}` is not an existing person id")


def unfiled(entries: list[Entry]) -> list[Entry]:
    return [
        entry
        for entry in entries
        if entry.type in ANCHOR_TYPES
        and entry.status == "active"
        and not entry.projects
        and not entry.people
    ]


def sort_entries(entries: list[Entry]) -> list[Entry]:
    """Sort by created descending, then ID ascending, for stable output."""
    ordered = sorted(entries, key=lambda entry: entry.id)
    ordered.sort(key=lambda entry: entry.created, reverse=True)
    return ordered


def esc(text: str) -> str:
    return text.replace("\\", "\\\\").replace("|", "\\|")


def render_table(rows: list[tuple], with_status: bool = False) -> str:
    if with_status:
        lines = ["| id | status | summary | path |", "|----|--------|---------|------|"]
        for entry_id, status, summary, path in rows:
            lines.append(f"| {entry_id} | {status} | {esc(summary)} | `{path}` |")
    else:
        lines = ["| id | summary | path |", "|----|---------|------|"]
        for entry_id, summary, path in rows:
            lines.append(f"| {entry_id} | {esc(summary)} | `{path}` |")
    if not rows:
        lines.append("| — | (none) | — |" if not with_status else "| — | — | (none) | — |")
    return "\n".join(lines) + "\n"


def rel_link(from_rel: str, to_rel: str) -> str:
    """Return a relative link that works in both Obsidian and plain Markdown."""
    return posixpath.relpath(to_rel, posixpath.dirname(from_rel) or ".")


def render_linked_table(from_rel: str, items: list[Entry]) -> str:
    lines = ["| id | status | summary |", "|----|--------|---------|"]
    for entry in items:
        lines.append(
            f"| [{entry.id}]({rel_link(from_rel, entry.path)}) | {entry.status} | {esc(entry.summary)} |"
        )
    return "\n".join(lines) + "\n"


def render_people_table(items: list[Entry], pages: set[str]) -> str:
    """Render people with project links to their aggregation pages."""
    lines = ["| id | projects | summary | path |", "|----|----------|---------|------|"]
    for entry in items:
        links = [
            f"[{slug}]({rel_link('moc/people.md', PROJECT_PAGE.format(slug=slug))})"
            if PROJECT_PAGE.format(slug=slug) in pages
            else slug
            for slug in entry.projects
        ]
        projects = "、".join(links) if links else "—"
        lines.append(f"| {entry.id} | {projects} | {esc(entry.summary)} | `{entry.path}` |")
    if not items:
        lines.append("| — | — | (none) | — |")
    return "\n".join(lines) + "\n"


def entries_for_slug(entries: list[Entry], slug: str) -> list[Entry]:
    """Return facts anchored to a project or stored under its directory."""
    return [
        entry
        for entry in entries
        if slug in entry.projects or entry.path.startswith(f"projects/{slug}/")
    ]


def project_groups(entries: list[Entry]) -> dict[str, list[Entry]]:
    """Group by project; omit projects with no active facts."""
    slugs = sorted(
        {
            entry.path.split("/")[1]
            for entry in entries
            if entry.path.startswith("projects/") and entry.path.count("/") >= 2
        }
    )
    groups: dict[str, list[Entry]] = {}
    for slug in slugs:
        members = entries_for_slug(entries, slug)
        if any(entry.status == "active" for entry in members):
            groups[slug] = members
    return groups


def project_page_block(
    from_rel: str, slug: str, members: list[Entry], persons: dict[str, Entry]
) -> str:
    """Render the project aggregation page."""
    visible = [entry for entry in members if entry.status != "archived"]
    active = [entry for entry in visible if entry.status == "active"]
    own = [
        entry
        for entry in active
        if entry.type == "project" and entry.path.startswith(f"projects/{slug}/")
    ]
    project_file = sort_entries(own)[0] if own else None

    # A person is related when their record lists this project or another
    # project-scoped fact references that person.
    basis: dict[str, list[str]] = {}
    for entry in visible:
        if entry.type == "person":
            basis.setdefault(entry.id, []).append("person record's project field")
    for entry in visible:
        if entry.type == "person":
            continue
        for person_id in entry.people:
            if person_id in persons:
                basis.setdefault(person_id, []).append(f"`{entry.id}` people field")

    lines: list[str] = []
    if project_file is not None:
        lines.append(
            f"- Project file: [{project_file.id}]({rel_link(from_rel, project_file.path)}) — "
            f"{esc(project_file.summary)}"
        )
    else:
        lines.append(f"- Project file: missing ({len(active)} active fact(s) in this directory)")
    lines.append("")
    lines.append(
        f"{len(active)} active fact(s)"
        + (f"; {len(basis)} related person(s)." if basis else ".")
    )

    if basis:
        lines.append("")
        lines.append("## People")
        lines.append("")
        lines.append("| person | basis | summary |")
        lines.append("|--------|------|---------|")
        for person_id in sorted(basis):
            person = persons[person_id]
            why = ", ".join(sorted(set(basis[person_id])))
            lines.append(
                f"| [{person.id}]({rel_link(from_rel, person.path)}) | {esc(why)} | "
                f"{esc(person.summary)} |"
            )

    section_types = {type_key for type_key, _ in PROJECT_SECTIONS}
    for type_key, label in PROJECT_SECTIONS:
        rows = sort_entries([entry for entry in visible if entry.type == type_key])
        if not rows:
            continue
        lines.append("")
        lines.append(f"## {label}")
        lines.append("")
        lines.append(render_linked_table(from_rel, rows).rstrip("\n"))

    others = [
        entry
        for entry in visible
        if entry.type not in section_types and entry.type not in {"person", "project"}
    ]
    if others:
        lines.append("")
        lines.append("## Other facts")
        lines.append("")
        lines.append(render_linked_table(from_rel, sort_entries(others)).rstrip("\n"))

    return "\n".join(lines) + "\n"


def build_blocks(entries: list[Entry]) -> dict[str, str]:
    active = [entry for entry in entries if entry.status == "active"]
    blocks: dict[str, str] = {}

    def moc_rows(entry_type: str, statuses: tuple[str, ...] = ("active",), with_status: bool = False) -> list[tuple]:
        selected = [item for item in entries if item.type == entry_type and item.status in statuses]
        ordered = sort_entries(selected)
        if with_status:
            return [(entry.id, entry.status, entry.summary, entry.path) for entry in ordered]
        return [(entry.id, entry.summary, entry.path) for entry in ordered]

    groups = project_groups(entries)
    pages = {PROJECT_PAGE.format(slug=slug) for slug in groups}

    blocks["moc/standing-rules.md"] = render_table(moc_rows("profile"))
    blocks["moc/people.md"] = render_people_table(
        sort_entries([entry for entry in entries if entry.type == "person" and entry.status == "active"]),
        pages,
    )
    blocks["moc/open-loops.md"] = render_table(moc_rows("open-loop"))
    # Decisions and journal notes keep history and expose status.
    history = ("active", "superseded")
    blocks["moc/decisions.md"] = render_table(moc_rows("decision", history, with_status=True), with_status=True)
    blocks["moc/journal.md"] = render_table(moc_rows("journal", history, with_status=True), with_status=True)
    blocks["moc/unfiled.md"] = render_table(
        [(entry.id, entry.summary, entry.path) for entry in sort_entries(unfiled(entries))]
    )

    # One aggregation page per project so related facts can be read together.
    persons = {entry.id: entry for entry in entries if entry.type == "person"}
    for slug, members in groups.items():
        page = PROJECT_PAGE.format(slug=slug)
        blocks[page] = project_page_block(page, slug, members, persons)

    profile_count = len([entry for entry in active if entry.type == "profile"])
    person_count = len([entry for entry in active if entry.type == "person"])
    open_loop_count = len([entry for entry in active if entry.type == "open-loop"])
    decision_count = len([entry for entry in entries if entry.type == "decision" and entry.status in history])
    journal_count = len([entry for entry in entries if entry.type == "journal" and entry.status in history])
    decisions = sort_entries([entry for entry in active if entry.type == "decision"])[:RECENT_DECISIONS]
    loose = sort_entries(unfiled(entries))

    lines: list[str] = []
    lines.append("## Standing rules")
    lines.append(f"- See `moc/standing-rules.md` — {profile_count} record(s)")
    lines.append("")
    lines.append("## Active projects")
    if groups:
        for slug, members in groups.items():
            own = [
                entry
                for entry in members
                if entry.status == "active"
                and entry.type == "project"
                and entry.path.startswith(f"projects/{slug}/")
            ]
            project_file = sort_entries(own)[0] if own else None
            fact_count = len([entry for entry in members if entry.status == "active"])
            page = PROJECT_PAGE.format(slug=slug)
            if project_file is not None:
                lines.append(f"- [{slug}]({page}) — {project_file.summary}")
            else:
                lines.append(
                    f"- [{slug}]({page}) — no project file; {fact_count} active fact(s) in the directory"
                )
    else:
        lines.append("- (none)")
    lines.append("")
    lines.append("## Recent decisions")
    if decisions:
        for entry in decisions:
            lines.append(f"- [{entry.id}]({entry.path}) — {entry.summary}")
    else:
        lines.append("- (none)")
    if decision_count:
        lines.append(f"- All {decision_count} record(s), including superseded, in `moc/decisions.md`")
    lines.append("")
    lines.append("## Open loops")
    lines.append(f"- See `moc/open-loops.md` — {open_loop_count} record(s)")
    lines.append("")
    lines.append("## People")
    lines.append(f"- See `moc/people.md` — {person_count} record(s)")
    lines.append("")
    lines.append("## Journal")
    lines.append(f"- See `moc/journal.md` — {journal_count} record(s)")
    lines.append("")
    lines.append("## Unfiled")
    lines.append(f"- See `moc/unfiled.md` — {len(loose)} record(s) without project/person anchors")
    blocks["INDEX.md"] = "\n".join(lines) + "\n"
    return blocks


def current_text(rel: str) -> str | None:
    path = ROOT / rel
    if not path.exists():
        return None
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise IndexReadError(rel, str(exc)) from exc


def merged_text(rel: str, block: str) -> str:
    text = current_text(rel)
    if text is None:
        return header_for(rel) + MARK_BEGIN + "\n" + block + MARK_END + "\n"
    if text.count(MARK_BEGIN) != 1 or text.count(MARK_END) != 1:
        raise MarkersMissing(rel)
    match = BLOCK_RE.search(text)
    if not match:
        raise MarkersMissing(rel)
    return text[: match.start(1)] + block + text[match.end(1):]


def suggest_links(entries: list[Entry], target_id: str) -> int:
    """Suggest candidates sharing a project anchor or tag; never modify files."""
    by_id = {entry.id: entry for entry in entries if entry.id}
    target = by_id.get(target_id)
    if target is None:
        print(f"error: id `{target_id}` not found", file=sys.stderr)
        return 2

    linked = set(target.links) | set(target.contradicts)
    if target.supersedes:
        linked.add(target.supersedes)
    for entry in entries:
        if target.id in entry.links or target.id in entry.contradicts:
            linked.add(entry.id)
        if entry.supersedes == target.id:
            linked.add(entry.id)

    candidates: list[tuple[int, Entry, list[str]]] = []
    for entry in entries:
        if entry.id == target.id or entry.id in linked or entry.status == "archived":
            continue
        if entry.type == "project":
            continue  # Project files are containers; the anchor already expresses membership.
        shared_projects = [slug for slug in target.projects if slug in entry.projects]
        shared_tags = [
            tag for tag in target.tags if tag in entry.tags and tag not in shared_projects
        ]
        score = 2 * len(shared_projects) + len(shared_tags)
        if score < 2:
            continue  # A single shared tag is too weak to justify an edge.
        why = [f"project {slug}" for slug in shared_projects] + [f"tag {tag}" for tag in shared_tags]
        candidates.append((score, entry, why))

    if not candidates:
        print("No candidates found: related records are already linked, or none are close enough.")
        return 0

    candidates.sort(key=lambda item: (item[0], item[1].created, item[1].id), reverse=True)
    print(f"Candidates for `{target.id}` ({len(candidates)}, highest relevance first):")
    for _score, entry, why in candidates[:SUGGEST_LIMIT]:
        print(f"- {entry.id}（{entry.type} / {entry.status}）{entry.summary}")
        print(f"  shared: {', '.join(why)}")
    print("")
    print("Add only confirmed related IDs to `links: [...]`; never bulk-backfill edges.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate and validate the long-term memory index")
    parser.add_argument("--check", action="store_true", help="validate only; exit 2 if the index is stale")
    parser.add_argument("--strict", action="store_true", help="treat missing anchors as errors")
    parser.add_argument(
        "--suggest-links",
        metavar="ID",
        help="read-only: list possible related records for an entry",
    )
    args = parser.parse_args(argv)

    errors: list[str] = []
    warnings: list[str] = []
    entries = load_entries(errors, warnings)
    validate_relations(entries, errors, warnings)

    if args.suggest_links:
        if errors:
            for message in errors:
                print(f"error: {message}", file=sys.stderr)
            return 2
        return suggest_links(entries, args.suggest_links)

    loose = unfiled(entries)
    for entry in loose:
        message = f"{entry.path}: missing project/person anchor (listed in moc/unfiled.md)"
        if args.strict:
            errors.append(message)
        else:
            warnings.append(message)

    if errors:
        for message in warnings:
            print(f"warning: {message}", file=sys.stderr)
        for message in errors:
            print(f"error: {message}", file=sys.stderr)
        print(
            f"\nIndex not generated: {len(errors)} error(s). Fix them and retry.",
            file=sys.stderr,
        )
        return 2

    for message in warnings:
        print(f"warning: {message}", file=sys.stderr)

    blocks = build_blocks(entries)
    for rel in blocks:
        target = ROOT / rel
        if target.is_symlink() or not inside_root(target):
            print(f"error: {rel} is a symlink or points outside the repository; refusing to write", file=sys.stderr)
            return 2
    rendered: dict[str, str] = {}
    try:
        for rel, block in blocks.items():
            rendered[rel] = merged_text(rel, block)
        stale = [rel for rel, text in rendered.items() if current_text(rel) != text]
    except MarkersMissing as exc:
        print(
            f"error: {exc.rel} has invalid index markers; expected exactly one "
            f"`{MARK_BEGIN}` / `{MARK_END}` pair",
            file=sys.stderr,
        )
        return 2
    except IndexReadError as exc:
        print(
            f"error: could not read {exc.rel} ({exc.detail}); check encoding and permissions",
            file=sys.stderr,
        )
        return 2

    # Remove obsolete pure-generated project pages.
    obsolete: list[str] = []
    for path in sorted((ROOT / "moc").glob("project-*.md")):
        rel = path.relative_to(ROOT).as_posix()
        if rel in blocks:
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            print(f"error: could not read {rel} ({exc}); skipped deletion check", file=sys.stderr)
            return 2
        if text.count(MARK_BEGIN) != 1 or text.count(MARK_END) != 1 or BLOCK_RE.search(text) is None:
            print(
                f"error: {rel} has no matching project and lacks valid markers; "
                "refusing to delete a possibly hand-edited file",
                file=sys.stderr,
            )
            return 2
        # Delete only pure-generated pages. Any hand-written content outside
        # the markers is outside the generator's ownership and must be reviewed.
        match = BLOCK_RE.search(text)
        assert match is not None
        if text[: match.start(1)] != header_for(rel) + MARK_BEGIN + "\n" or text[match.end():] != "\n":
            print(
                f"error: {rel} has no matching project but contains hand-written content "
                "outside the markers; review and remove it manually",
                file=sys.stderr,
            )
            return 2
        obsolete.append(rel)

    if args.check:
        if stale or obsolete:
            if stale:
                print("Generated index is stale; regenerate these files:", file=sys.stderr)
                for rel in stale:
                    print(f"  - {rel}", file=sys.stderr)
            if obsolete:
                print("These project pages no longer have a matching project:", file=sys.stderr)
                for rel in obsolete:
                    print(f"  - {rel}", file=sys.stderr)
            print("Run `python3 scripts/build_memory_index.py` to repair.", file=sys.stderr)
            return 2
        print(f"Index is current ({len(rendered)} files).")
        return 0

    for rel in stale:
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered[rel], encoding="utf-8")
    for rel in obsolete:
        (ROOT / rel).unlink()
    if stale:
        print(f"Updated index: {', '.join(stale)}")
    if obsolete:
        print(f"Removed obsolete project page(s): {', '.join(obsolete)}")
    if not stale and not obsolete:
        print("Index is already current; no changes.")
    if loose:
        print(f"hint: {len(loose)} record(s) lack a project/person anchor; see moc/unfiled.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
